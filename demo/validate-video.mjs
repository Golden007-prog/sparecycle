import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..');
const deepDive=process.argv.includes('--deep-dive');
const output=path.join(root,'test-results/video',...(deepDive?['deep-dive']:[]));
const file=path.join(output,deepDive?'sparecycle-backend-deep-dive.mp4':'sparecycle-review-demo.mp4');
const decode=spawnSync('ffmpeg',['-hide_banner','-v','error','-i',file,'-f','null','NUL'],{cwd:root,encoding:'utf8'});
if(decode.status!==0)throw new Error(decode.stderr);
const p=spawnSync('ffmpeg',['-hide_banner','-i',file,'-af','loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json,silencedetect=noise=-40dB:d=1.8','-vn','-f','null','NUL'],{cwd:root,encoding:'utf8'});
if(p.status!==0)throw new Error(p.stderr);
const match=p.stderr.match(/\{\s*"input_i"[\s\S]*?\}/);
if(!match)throw new Error('Missing audio measurements');
const audio=JSON.parse(match[0]);
const evidenceFile=path.join(output,'render-evidence.json');
const evidence=JSON.parse(fs.readFileSync(evidenceFile,'utf8'));
evidence.validation={decodeExit:0,textBounds:'all scenes fit',visualReview:'inspect poster and contact sheet separately',audioMeasurements:audio,silenceOver1_8Seconds:/silence_start/.test(p.stderr),auralListening:false};
fs.writeFileSync(evidenceFile,JSON.stringify(evidence,null,2));
console.log(evidence.validation);
