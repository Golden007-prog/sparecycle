import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..');
const deepDive=process.argv.includes('--deep-dive');
const output=path.join(root,'test-results/video',...(deepDive?['deep-dive']:[]));
const file=path.join(output,deepDive?'sparecycle-backend-deep-dive.mp4':'sparecycle-review-demo.mp4');
const probe=spawnSync('ffprobe',['-v','error','-show_format','-show_streams','-of','json',file],{cwd:root,encoding:'utf8'});
if(probe.status!==0)throw new Error(probe.stderr);
const media=JSON.parse(probe.stdout);
const duration=Number(media.format.duration);
const video=media.streams.find(stream=>stream.codec_type==='video');
const sound=media.streams.find(stream=>stream.codec_type==='audio');
if(video?.width!==1920 || video?.height!==1080 || video?.codec_name!=='h264' || sound?.codec_name!=='aac')throw new Error('Expected 1080p H.264 with AAC audio.');
if(!deepDive && duration>=180)throw new Error('Competition cut must remain under 180 seconds.');
const decode=spawnSync('ffmpeg',['-hide_banner','-v','error','-i',file,'-f','null','NUL'],{cwd:root,encoding:'utf8'});
if(decode.status!==0)throw new Error(decode.stderr);
const webDecode=spawnSync('ffmpeg',['-hide_banner','-v','error','-i',path.join(output,'assembly.mp4'),'-f','null','NUL'],{cwd:root,encoding:'utf8'});
if(webDecode.status!==0)throw new Error(webDecode.stderr);
const p=spawnSync('ffmpeg',['-hide_banner','-i',file,'-af','loudnorm=I=-16:TP=-1.5:LRA=11:print_format=json,silencedetect=noise=-40dB:d=1.8','-vn','-f','null','NUL'],{cwd:root,encoding:'utf8'});
if(p.status!==0)throw new Error(p.stderr);
const match=p.stderr.match(/\{\s*"input_i"[\s\S]*?\}/);
if(!match)throw new Error('Missing audio measurements');
const audio=JSON.parse(match[0]);
const evidenceFile=path.join(output,'render-evidence.json');
const evidence=JSON.parse(fs.readFileSync(evidenceFile,'utf8'));
const scenes=JSON.parse(fs.readFileSync(path.join(root,'demo',deepDive?'storyboard-deep-dive.json':'storyboard.json'),'utf8'));
if(JSON.stringify(scenes.map(scene=>scene.id))!==JSON.stringify(evidence.scenes.map(scene=>scene.id)))throw new Error('Evidence does not match the current storyboard.');
const vtt=fs.readFileSync(file.replace(/\.mp4$/,'.vtt'),'utf8');
const clock=text=>text.split(':').reduce((total,part)=>total*60+Number(part),0);
const cues=[...vtt.matchAll(/(\d{2}:\d{2}:\d{2}\.\d{3}) --> (\d{2}:\d{2}:\d{2}\.\d{3})/g)].map(match=>({start:clock(match[1]),end:clock(match[2])}));
if(cues.length!==scenes.reduce((total,scene)=>total+scene.captions.length,0))throw new Error('Caption count differs from narration.');
let last=0;
for(const cue of cues){if(cue.start<last || cue.end<=cue.start || cue.end>duration)throw new Error('Caption timing is invalid.');last=cue.end;}
if(Number(audio.input_tp)>=0)throw new Error('Audio peak clips.');
evidence.validation={decodeExit:0,webDecodeExit:0,actualDuration:duration,format:'1920×1080 H.264 / AAC',captionCount:cues.length,captionBounds:'valid ordered cues within media',competitionLimit:deepDive?'not applicable':duration<180,textBounds:'all scenes fit',visualReview:'inspect poster and contact sheet separately',audioMeasurements:audio,silenceOver1_8Seconds:/silence_start/.test(p.stderr),auralListening:false};
fs.writeFileSync(evidenceFile,JSON.stringify(evidence,null,2));
console.log(evidence.validation);
